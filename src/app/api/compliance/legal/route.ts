import { NextResponse, type NextRequest } from "next/server";
import { renderPlain } from "@/lib/legal";
import { requireArea } from "@/lib/staff";
import { createZip, type ZipEntry } from "@/lib/zip";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";
export const maxDuration = 60;

const clean = (s: string) => s.replace(/[^a-zA-Z0-9-_. ]/g, "").replace(/\s+/g, "-").slice(0, 80);
const csvCell = (v: unknown) => {
  const s = v == null ? "" : String(v);
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};

/** One file holding everything: every version's wording, uploaded files, acceptances and a manifest. */
export async function GET(req: NextRequest) {
  const { supabase } = await requireArea("legal");
  const includeFiles = req.nextUrl.searchParams.get("files") !== "no";
  const [{ data: docs }, { data: versions }, { data: files }, { data: acceptances }, { data: settings }] = await Promise.all([
    supabase.from("legal_documents").select("*").order("display_order").order("id"),
    supabase.from("legal_document_versions").select("*").order("legal_document_id").order("created_at"),
    supabase.from("legal_files").select("*"),
    supabase.from("acceptance_record").select("*").limit(20000),
    supabase.from("platform_settings").select("setting_key, setting_value").eq("setting_group", "Legal entity"),
  ]);
  const entity = Object.fromEntries((settings ?? []).map((s) => [s.setting_key, s.setting_value ?? ""]));
  const entityName = entity.legal_entity_name || "[Legal entity not set]";
  const stamp = new Date();
  const dateStr = stamp.toISOString().slice(0, 10);
  const entries: ZipEntry[] = [];
  const versionsFor = (id: number) => (versions ?? []).filter((v) => v.legal_document_id === id);
  const filesFor = (id: number) => (files ?? []).filter((f) => f.legal_document_id === id);

  entries.push({
    path: "README.txt",
    data: [
      "COACH PLATFORM — LEGAL ARCHIVE",
      `Exported ${stamp.toLocaleString("en-AU", { timeZone: "Australia/Brisbane" })}`,
      "",
      entityName,
      entity.abn ? `ABN ${entity.abn}` : "",
      entity.registered_address ?? "",
      "",
      "WHAT THIS IS",
      "",
      "A complete copy of every legal document held at the date above: the wording of",
      "every version, the files uploaded against each document, and the record of who",
      "accepted what. It's a point-in-time copy; the live version is in the portal.",
      "",
      "HOW IT IS ORGANISED",
      "",
      "  manifest.md            every document, its status and its versions",
      "  documents/{slug}/      one folder per document",
      "    document.txt         what it is, who it's for, where it's used",
      "    {version}.md         the wording of each version, in Markdown",
      "    {version}.txt        the same wording as plain text",
      "  files/{slug}/          PDFs and signed copies as uploaded",
      "  acceptances.csv        who accepted which version, and when",
      "",
      "ON VERSIONS",
      "",
      "A document is never edited in place once accepted. When wording changes, the old",
      "version keeps its text and gains an end date, so what was in force on any date",
      "can be produced.",
      "",
      `Generated by the Coach Platform internal portal · ${dateStr}`,
    ].join("\n"),
  });

  const manifest: string[] = [
    "# Legal archive manifest", "",
    `**Exported** ${stamp.toLocaleString("en-AU", { timeZone: "Australia/Brisbane" })}`,
    `**Entity** ${entityName}`,
    entity.abn ? `**ABN** ${entity.abn}` : "",
    "", "---", "",
    `${(docs ?? []).length} documents · ${(versions ?? []).length} versions · ${(files ?? []).length} files · ${(acceptances ?? []).length} acceptances`,
    "",
  ];
  const byCategory = new Map<string, typeof docs>();
  for (const d of docs ?? []) byCategory.set(d.category ?? "Uncategorised", [...(byCategory.get(d.category ?? "Uncategorised") ?? []), d]);
  for (const [cat, list] of byCategory) {
    manifest.push(`## ${cat}`, "", "| Document | For | Versions | Files | Status |", "|---|---|---|---|---|");
    for (const d of list ?? []) {
      const vs = versionsFor(d.id);
      const current = vs.find((v) => v.is_current);
      manifest.push(`| ${d.name} | ${d.document_type} | ${vs.length}${current ? ` (current from ${current.effective_from ?? "—"})` : " — none current"} | ${filesFor(d.id).length} | ${d.archived_at ? "Archived" : d.is_published ? "Published" : d.doc_status} |`);
    }
    manifest.push("");
  }
  entries.push({ path: "manifest.md", data: manifest.filter((l) => l !== null).join("\n") });

  for (const d of docs ?? []) {
    const folder = `documents/${clean(d.slug)}`;
    entries.push({
      path: `${folder}/document.txt`,
      data: [
        d.name, "=".repeat(d.name.length), "",
        `Slug            ${d.slug}`,
        `For             ${d.document_type}`,
        `Category        ${d.category ?? "—"}`,
        `Jurisdiction    ${d.jurisdiction ?? "—"}`,
        `Status          ${d.doc_status}${d.archived_at ? " (archived)" : ""}`,
        `Published       ${d.is_published ? "Yes" : "No"}`,
        `Acceptance      ${d.requires_acceptance ? "Required" : "Not required"}`,
        `Review due      ${d.review_due ?? "—"}`,
        "",
        d.summary ? `Summary\n  ${d.summary}` : "",
        (d.used_on ?? []).length ? `\nUsed on\n${(d.used_on ?? []).map((u: string) => `  · ${u}`).join("\n")}` : "",
        d.owner_note ? `\nNote\n  ${d.owner_note}` : "",
        d.archive_reason ? `\nArchived because\n  ${d.archive_reason}` : "",
      ].filter(Boolean).join("\n"),
    });
    for (const v of versionsFor(d.id)) {
      if (!v.body) continue;
      const label = clean(v.version_label ?? v.effective_from ?? String(v.id));
      const header = [
        `# ${d.name}`, "",
        `Version: ${v.version_label ?? "—"}`,
        `In force from: ${v.effective_from ?? "—"}`,
        `In force to: ${v.effective_to ?? (v.is_current ? "Current" : "—")}`,
        v.change_summary ? `What changed: ${v.change_summary}` : "",
        v.approved_by ? `Approved by: ${v.approved_by}` : "",
        "", "---", "",
      ].filter(Boolean).join("\n");
      entries.push({ path: `${folder}/${label}.md`, data: header + v.body });
      entries.push({ path: `${folder}/${label}.txt`, data: renderPlain(header + v.body) });
    }
  }

  let fileCount = 0;
  if (includeFiles) {
    for (const f of files ?? []) {
      const doc = (docs ?? []).find((d) => d.id === f.legal_document_id);
      const dir = `files/${clean(doc?.slug ?? "unfiled")}`;
      if (!f.storage_path) {
        if (f.external_url) entries.push({ path: `${dir}/${clean(f.file_name)}.link.txt`, data: f.external_url });
        continue;
      }
      try {
        const { data } = await supabase.storage.from("legal").download(f.storage_path);
        if (!data) continue;
        entries.push({ path: `${dir}/${clean(f.file_name)}`, data: new Uint8Array(await data.arrayBuffer()) });
        fileCount++;
      } catch {
        entries.push({ path: `${dir}/MISSING-${clean(f.file_name)}.txt`, data: `This file couldn't be read from storage at export time.\nPath: ${f.storage_path}` });
      }
    }
  }

  const rows = [["Document", "Version", "Accepted by", "Email", "Business", "Accepted at", "Source", "Fingerprint", "Wording"].join(",")];
  for (const a of acceptances ?? []) rows.push([a.document, a.version, a.signatory_name, a.signatory_email, a.coach_business, a.accepted_at, a.source, a.fingerprint, a.integrity].map(csvCell).join(","));
  entries.push({ path: "acceptances.csv", data: rows.join("\r\n") });

  const zip = createZip(entries, stamp);
  await supabase.from("compliance_exports").insert({
    export_kind: "Legal",
    documents_count: (docs ?? []).length,
    versions_count: (versions ?? []).length,
    files_count: fileCount,
    acceptances_count: (acceptances ?? []).length,
    size_bytes: zip.length,
    notes: includeFiles ? null : "Wording only",
  });
  return new NextResponse(zip as unknown as BodyInit, {
    headers: {
      "Content-Type": "application/zip",
      "Content-Disposition": `attachment; filename="legal-archive-${dateStr}.zip"`,
      "Content-Length": String(zip.length),
    },
  });
}
